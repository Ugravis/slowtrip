import { CHUNK_SIZE } from '../../world/constants'
import { FEATURE_REGION, type MapFeature } from '../../world/terrain/mapFeatures'
import { MAP_TILE_PX, type MapLayer } from '../../world/terrain/mapTile'
import type { MapOverview, MapTileSource } from '../../world/terrain/mapTiles'
import { packChunk, unpackChunkX, unpackChunkZ } from '../../world/terrain/TerrainSystem'

const STEP = CHUNK_SIZE / MAP_TILE_PX
/** Max tile requests in flight to the map worker. */
const MAX_IN_FLIGHT = 4
/** Tile cache size per layer (32x32 bitmaps, ~4 KB each). Fits a dev reveal of radius 32. */
const MAX_TILES = 4000
/** Max feature region requests in flight. */
const MAX_FEATURES_IN_FLIGHT = 2
/** Peak and pass altitudes are labelled at or below this zoom (m/px), when labels are on. */
const LABEL_ZOOM = 6
/** Unexplored area. */
const FOG = '#1c2430'
/** Explored, tile not generated yet. */
const PENDING = '#3b4a3a'

export interface MinimapView {
  /** World position shown at the viewport center (float64, not local). */
  centerX: number
  centerZ: number
  /** World position of the player. */
  playerX: number
  playerZ: number
  /** Heading in radians, forward = (-sin h, -cos h). */
  heading: number
  /** Meters per CSS pixel. */
  zoom: number
  /** Heading-up when true, north-up otherwise. */
  rotate: boolean
  /** Draws the "N" marker on a round rim (minimap only). */
  northMarker: boolean
  layer: MapLayer
  /** Altitude labels next to peaks and passes (full map). */
  labels: boolean
  /** Dev overview drawn under the explored tiles, whatever was explored (full map). */
  overview: MapOverview | null
}

export interface MinimapMarker {
  x: number
  z: number
  color: string
}

/**
 * Draws a top-down terrain map, only over chunks the player has explored (loaded by the terrain
 * system). Tiles are generated by a worker (nearest first) and cached per layer, so zooming out
 * never generates new terrain. World coordinates stay in JS doubles: canvas transforms only see
 * offsets relative to the view center.
 */
export class MinimapRenderer {
  private readonly tiles: Record<MapLayer, Map<number, ImageBitmap>> = {
    terrain: new Map(),
    biomes: new Map(),
  }
  private readonly requested: Record<MapLayer, Set<number>> = {
    terrain: new Set(),
    biomes: new Set(),
  }
  /** Visible tiles not generated yet, nearest last (popped first). Rebuilt on each draw. */
  private queue: { key: number; d: number }[] = []
  private queueLayer: MapLayer = 'terrain'
  private inFlight = 0
  /** Peaks and passes per feature region (packed region coords). Small: never evicted. */
  private readonly features = new Map<number, MapFeature[]>()
  private readonly featuresRequested = new Set<number>()
  private featuresInFlight = 0
  private readonly visibleRegions = new Set<number>()

  constructor(
    private readonly source: MapTileSource,
    private readonly explored: ReadonlySet<number>,
  ) {}

  draw(
    ctx: CanvasRenderingContext2D,
    width: number,
    height: number,
    dpr: number,
    view: MinimapView,
    markers: readonly MinimapMarker[],
    markerCount: number,
  ): void {
    const hw = width / 2
    const hh = height / 2
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0)
    ctx.fillStyle = FOG
    ctx.fillRect(0, 0, width, height)

    ctx.save()
    ctx.translate(hw, hh)
    if (view.rotate) ctx.rotate(view.heading)
    const k = 1 / view.zoom
    ctx.scale(k, k)

    // Visible world radius (covers the corners when rotated).
    const r = Math.hypot(hw, hh) * view.zoom + CHUNK_SIZE
    const ox = view.centerX
    const oz = view.centerZ
    const pcx = view.playerX / CHUNK_SIZE
    const pcz = view.playerZ / CHUNK_SIZE
    const tiles = this.tiles[view.layer]
    const requested = this.requested[view.layer]
    const queue: { key: number; d: number }[] = []
    this.visibleRegions.clear()
    const ov = view.overview
    if (ov) {
      ctx.imageSmoothingEnabled = view.zoom > ov.scale * 0.5
      ctx.drawImage(
        ov.bitmap,
        ov.x0 - ox,
        ov.z0 - oz,
        ov.bitmap.width * ov.scale,
        ov.bitmap.height * ov.scale,
      )
    }
    // One screen pixel of overlap hides antialiased seams between scaled tiles.
    const seam = CHUNK_SIZE + view.zoom
    ctx.imageSmoothingEnabled = view.zoom > STEP * 0.5
    // Iterate explored chunks, not the view rectangle: cost is bounded by exploration,
    // whatever the zoom.
    for (const key of this.explored) {
      const cx = unpackChunkX(key)
      const cz = unpackChunkZ(key)
      const x = cx * CHUNK_SIZE - ox
      const z = cz * CHUNK_SIZE - oz
      if (x > r || z > r || x + CHUNK_SIZE < -r || z + CHUNK_SIZE < -r) continue
      this.visibleRegions.add(
        packChunk(Math.floor(cx / FEATURE_REGION), Math.floor(cz / FEATURE_REGION)),
      )
      const tile = tiles.get(key)
      if (!tile) {
        ctx.fillStyle = PENDING
        ctx.fillRect(x, z, seam, seam)
        if (!requested.has(key)) {
          queue.push({ key, d: (cx + 0.5 - pcx) ** 2 + (cz + 0.5 - pcz) ** 2 })
        }
        continue
      }
      // Touch for LRU order.
      tiles.delete(key)
      tiles.set(key, tile)
      ctx.drawImage(tile, x, z, seam, seam)
    }

    for (let i = 0; i < markerCount; i++) {
      const m = markers[i] as MinimapMarker
      ctx.fillStyle = m.color
      ctx.beginPath()
      ctx.arc(m.x - ox, m.z - oz, 4 * view.zoom, 0, Math.PI * 2)
      ctx.fill()
    }

    this.drawFeatures(ctx, view, r)

    // Player arrow, constant screen size.
    ctx.translate(view.playerX - ox, view.playerZ - oz)
    ctx.scale(view.zoom, view.zoom)
    ctx.rotate(-view.heading)
    ctx.fillStyle = '#fff'
    ctx.strokeStyle = 'rgb(0 0 0 / 60%)'
    ctx.lineWidth = 1.5
    ctx.beginPath()
    ctx.moveTo(0, -8)
    ctx.lineTo(6, 6)
    ctx.lineTo(0, 3)
    ctx.lineTo(-6, 6)
    ctx.closePath()
    ctx.stroke()
    ctx.fill()
    ctx.restore()

    if (view.northMarker) {
      ctx.save()
      ctx.translate(hw, hh)
      if (view.rotate) ctx.rotate(view.heading)
      ctx.fillStyle = '#fff'
      ctx.font = '600 11px system-ui, sans-serif'
      ctx.textAlign = 'center'
      ctx.textBaseline = 'middle'
      ctx.fillText('N', 0, -hh + 9)
      ctx.restore()
    }

    this.requestFeatures()
    queue.sort((a, b) => b.d - a.d)
    this.queue = queue
    this.queueLayer = view.layer
    this.pump()
  }

  /** Sends queued tile requests to the worker; refills as results arrive, not only per draw. */
  private pump(): void {
    const layer = this.queueLayer
    while (this.inFlight < MAX_IN_FLIGHT && this.queue.length > 0) {
      const { key } = this.queue.pop() as { key: number }
      const requested = this.requested[layer]
      if (requested.has(key) || this.tiles[layer].has(key)) continue
      requested.add(key)
      this.inFlight++
      void this.source.tile(unpackChunkX(key), unpackChunkZ(key), layer).then((bitmap) => {
        this.inFlight--
        requested.delete(key)
        this.store(layer, key, bitmap)
        this.pump()
      })
    }
  }

  /** Peak and pass markers at constant screen size, upright, over explored chunks only. */
  private drawFeatures(ctx: CanvasRenderingContext2D, view: MinimapView, r: number): void {
    const labels = view.labels && view.zoom <= LABEL_ZOOM
    const angle = view.rotate ? -view.heading : 0
    ctx.lineJoin = 'round'
    ctx.font = '600 11px system-ui, sans-serif'
    ctx.textBaseline = 'middle'
    for (const region of this.visibleRegions) {
      const list = this.features.get(region)
      if (!list) continue
      for (const f of list) {
        const x = f.x - view.centerX
        const z = f.z - view.centerZ
        if (Math.abs(x) > r || Math.abs(z) > r) continue
        if (
          !this.explored.has(packChunk(Math.floor(f.x / CHUNK_SIZE), Math.floor(f.z / CHUNK_SIZE)))
        )
          continue
        ctx.save()
        ctx.translate(x, z)
        ctx.scale(view.zoom, view.zoom)
        ctx.rotate(angle)
        ctx.lineWidth = 3
        ctx.strokeStyle = 'rgb(255 255 255 / 85%)'
        ctx.beginPath()
        if (f.kind === 'peak') {
          ctx.moveTo(0, -5)
          ctx.lineTo(5, 4)
          ctx.lineTo(-5, 4)
          ctx.closePath()
          ctx.stroke()
          ctx.fillStyle = '#3a2c22'
          ctx.fill()
        } else {
          // Pass: ")(" between two slopes.
          ctx.arc(-6, 0, 5, -Math.PI / 3, Math.PI / 3)
          ctx.moveTo(6 + 5 * Math.cos((Math.PI * 2) / 3), 5 * Math.sin((Math.PI * 2) / 3))
          ctx.arc(6, 0, 5, (Math.PI * 2) / 3, (Math.PI * 4) / 3)
          ctx.stroke()
          ctx.lineWidth = 1.5
          ctx.strokeStyle = '#3a2c22'
          ctx.stroke()
        }
        if (labels) {
          const text = `${Math.round(f.height)} m`
          ctx.lineWidth = 3
          ctx.strokeStyle = 'rgb(0 0 0 / 55%)'
          ctx.strokeText(text, 9, 0)
          ctx.fillStyle = '#fff'
          ctx.fillText(text, 9, 0)
        }
        ctx.restore()
      }
    }
  }

  private requestFeatures(): void {
    for (const region of this.visibleRegions) {
      if (this.featuresInFlight >= MAX_FEATURES_IN_FLIGHT) return
      if (this.features.has(region) || this.featuresRequested.has(region)) continue
      this.featuresRequested.add(region)
      this.featuresInFlight++
      void this.source.features(unpackChunkX(region), unpackChunkZ(region)).then((list) => {
        this.featuresInFlight--
        this.featuresRequested.delete(region)
        this.features.set(region, list)
        this.requestFeatures()
      })
    }
  }

  private store(layer: MapLayer, key: number, bitmap: ImageBitmap): void {
    const tiles = this.tiles[layer]
    tiles.set(key, bitmap)
    while (tiles.size > MAX_TILES) {
      const oldest = tiles.keys().next().value
      if (oldest === undefined) break
      tiles.get(oldest)?.close()
      tiles.delete(oldest)
    }
  }
}
